/**
 * Regenerate hitbox-config.js from hitbox-config.json
 *
 * This script reads the JSON config and generates the JavaScript version
 * with proper formatting and the helper functions.
 *
 * Usage: node sprite-editor/regenerate-hitbox-config.js
 */

const fs = require('fs');
const path = require('path');

const JSON_FILE = path.join(__dirname, '..', 'scripts', 'hitbox-config.json');
const JS_FILE = path.join(__dirname, '..', 'scripts', 'hitbox-config.js');

console.log('🔄 Regenerating hitbox-config.js from JSON...\n');

// Read JSON config
const config = JSON.parse(fs.readFileSync(JSON_FILE, 'utf8'));

// Helper function to format object with proper indentation
function formatObject(obj, indent = '    ') {
    const entries = Object.entries(obj);
    if (entries.length === 0) return '{}';

    const lines = entries.map(([key, value]) => {
        if (typeof value === 'object' && !Array.isArray(value)) {
            // Nested object
            const valueStr = formatObject(value, indent + '    ');
            return `${indent}    "${key}": ${valueStr}`;
        } else {
            // Primitive value
            return `${indent}    "${key}": ${JSON.stringify(value)}`;
        }
    });

    return `{\n${lines.join(',\n')}\n${indent}}`;
}

// Generate the JavaScript file content
const jsContent = `// Hitbox and Shadow Configuration for Enemies
// This file is generated by the sprite editor and loaded by the game
// Last updated: ${new Date().toISOString()}

console.log('hitbox-config.js is loading...');

// Check if hitboxConfig already exists to avoid redeclaration
if (typeof hitboxConfig === 'undefined') {
    console.log('Creating hitboxConfig object...');
    var hitboxConfig = {
    loaded: false,

    // Load configuration (called when game starts)
    load: function() {
        this.loaded = true;
        console.log('Hitbox configuration loaded');
        console.log('Available scales:', Object.keys(this.scales).length);
        console.log('Available hitboxes:', Object.keys(this.hitboxes).length);

        // Validate hitbox configurations
        const invalidHitboxes = [];
        for (const [enemy, config] of Object.entries(this.hitboxes)) {
            if (!config.width || !config.height ||
                config.offsetX === undefined || config.offsetY === undefined) {
                invalidHitboxes.push(enemy);
            }
        }

        if (invalidHitboxes.length > 0) {
            console.warn('⚠️ Incomplete hitbox configs for:', invalidHitboxes.join(', '));
        } else {
            console.log('✅ All hitbox configurations are valid');
        }

        return true;
    },

    // Flip configurations - used for initial sprite orientation
    flips: ${formatObject(config.flips || {})},

    // Scale configurations for sprites
    scales: ${formatObject(config.scales || {})},

    // Hitbox configurations for each enemy type
    hitboxes: ${formatObject(config.hitboxes || {})},

    // Shadow configurations for each enemy type
    shadows: ${formatObject(config.shadows || {})},

    // Helper function to get scale configuration
    getScale: function(spriteType) {
        return this.scales[spriteType] || 1.0;
    },

    // Helper function to apply scale
    applyScale: function(sprite, spriteType) {
        const scale = this.getScale(spriteType);
        sprite.setScale(scale);
        return scale;
    },

    // Helper function to get flip configuration
    getFlip: function(spriteType) {
        return this.flips[spriteType] || { flipX: false, flipY: false };
    },

    // Helper function to apply flip configuration
    applyFlip: function(sprite, spriteType) {
        const flip = this.getFlip(spriteType);
        if (flip.flipX) sprite.setFlipX(true);
        if (flip.flipY) sprite.setFlipY(true);
        return flip;
    },

    // Helper function to apply hitbox configuration
    applyHitbox: function(enemy, enemyType) {
        const config = this.hitboxes[enemyType];
        if (!config) {
            console.error(\`[HITBOX] No config found for \${enemyType} - this should not happen!\`);
            return false;
        }

        if (!config.width || !config.height ||
            config.offsetX === undefined || config.offsetY === undefined) {
            console.error(\`[HITBOX] Invalid config for \${enemyType}:\`, config);
            return false;
        }

        console.log(\`[HITBOX] Applying for \${enemyType}:\`, config);
        console.log(\`[HITBOX] Sprite info - Scale: \${enemy.scaleX}, Origin: (\${enemy.originX}, \${enemy.originY})\`);
        console.log(\`[HITBOX] Sprite dimensions - Width: \${enemy.width}, Height: \${enemy.height}\`);
        console.log(\`[HITBOX] Flip state - flipX: \${enemy.flipX}, flipY: \${enemy.flipY}\`);

        // The sprite editor saves offsets in unscaled sprite coordinates
        // Phaser's body.setOffset() always uses unscaled coordinates
        // DO NOT divide by scale - apply directly
        enemy.body.setSize(config.width, config.height);
        enemy.body.setOffset(config.offsetX, config.offsetY);

        console.log(\`[HITBOX] Applied - Size: \${config.width}x\${config.height}, Offset: (\${config.offsetX}, \${config.offsetY})\`);

        return true;
    },

    // Helper function to get shadow configuration
    getShadow: function(enemyType) {
        return this.shadows[enemyType] || this.shadows[''] || { width: 30, height: 10, offsetX: 0, offsetY: 0, alpha: 0.3 };
    },

    // Update configuration from sprite editor export
    updateFromEditor: function(editorData) {
        if (editorData.scales) {
            Object.assign(this.scales, editorData.scales);
        }
        if (editorData.hitboxes) {
            Object.assign(this.hitboxes, editorData.hitboxes);
        }
        if (editorData.shadows) {
            Object.assign(this.shadows, editorData.shadows);
        }
        if (editorData.flips) {
            Object.assign(this.flips, editorData.flips);
        }
    }
};

    // Make available globally if in browser/Electron
    if (typeof window !== 'undefined') {
        window.hitboxConfig = hitboxConfig;
    }

    // Export for Node.js/require
    if (typeof module !== 'undefined' && module.exports) {
        module.exports = hitboxConfig;
    }

    console.log('hitboxConfig created successfully');
} else {
    console.log('hitboxConfig already exists, skipping creation');
}

console.log('hitbox-config.js finished loading');
`;

// Write the JavaScript file
fs.writeFileSync(JS_FILE, jsContent);

console.log('✅ Generated hitbox-config.js');
console.log(`   Flips: ${Object.keys(config.flips || {}).length} entries`);
console.log(`   Scales: ${Object.keys(config.scales || {}).length} entries`);
console.log(`   Hitboxes: ${Object.keys(config.hitboxes || {}).length} entries`);
console.log(`   Shadows: ${Object.keys(config.shadows || {}).length} entries`);

console.log('\n📝 Next Steps:');
console.log('   1. Test the game to verify all configs load correctly');
console.log('   2. Check browser console for any validation warnings');
console.log('   3. If all looks good, proceed to remove fallback code');
